// Builds the data for the "Night Circle" logo draw animation.
//
//   npm run logo:draw   → writes src/components/home/logo/logoPaths.js
//
// Source: public/images/night-circle-logo.svg (filled shapes, absolute M / L / C / Z paths).
// Run it again whenever the logo file changes.
//
// For every stroke of the lettering we trace the pen's path through its middle
// (scripts/lib/centerline.mjs). LogoDraw moves a pen along these paths, one after
// another from the far left to the right, and the solid white logo appears behind it.

import fs from "node:fs";
import path from "node:path";
import { centerlineStrokes } from "./lib/centerline.mjs";

const LOGO_FILE = "public/images/night-circle-logo.svg";
const OUT_FILE = "src/components/home/logo/logoPaths.js";
const S = 4; // raster resolution per logo unit (the logo has fine hairlines)

const svg = fs.readFileSync(LOGO_FILE, "utf8");
const viewBox = svg.match(/viewBox="([^"]+)"/)[1].split(/[\s,]+/).map(Number);
const ds = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1].replace(/\s+/g, " ").trim());

// path data → opentype-style commands (what centerline.mjs expects)
function parse(d) {
  const tokens = d.match(/[MLCZmlcz]|-?\d*\.?\d+(?:e-?\d+)?/g);
  const cmds = [];
  let i = 0, op = null;
  const num = () => parseFloat(tokens[i++]);
  while (i < tokens.length) {
    if (/[A-Za-z]/.test(tokens[i])) op = tokens[i++];
    if (op === "M") { cmds.push({ type: "M", x: num(), y: num() }); op = "L"; }
    else if (op === "L") cmds.push({ type: "L", x: num(), y: num() });
    else if (op === "C") cmds.push({ type: "C", x1: num(), y1: num(), x2: num(), y2: num(), x: num(), y: num() });
    else if (op === "Z" || op === "z") { cmds.push({ type: "Z" }); op = null; }
    else throw new Error(`Unsupported path command "${op}" — export the logo with absolute M/L/C/Z paths`);
  }
  return cmds;
}

function bboxOf(cmds) {
  const xs = [], ys = [];
  for (const c of cmds) for (const [kx, ky] of [["x", "y"], ["x1", "y1"], ["x2", "y2"]]) if (kx in c) { xs.push(c[kx]); ys.push(c[ky]); }
  return { x1: Math.min(...xs), y1: Math.min(...ys), x2: Math.max(...xs), y2: Math.max(...ys) };
}

// pen strokes of every shape, each running left → right, then all sorted by where they start
const pens = ds
  .flatMap((d) => {
    const cmds = parse(d);
    return centerlineStrokes(cmds, bboxOf(cmds), { S, minLen: 3, leftToRight: true }).strokes;
  })
  .map((k) => ({ ...k, x: parseFloat(k.d.slice(1)) }))
  .sort((a, b) => a.x - b.x)
  .map(({ d, len, width }) => ({ d, len, width }));

const file = `// AUTO-GENERATED by scripts/generate-logo-draw.mjs from ${LOGO_FILE} — do not edit by hand.
// FILLS: the logo's filled shapes, exactly as in the artwork
// PENS:  pen paths through the middle of every stroke, in drawing order (left → right),
//        with the pen width needed to cover the ink

export const VIEWBOX = ${JSON.stringify(viewBox)};

export const FILLS = ${JSON.stringify(ds, null, 2)};

export const PENS = ${JSON.stringify(pens, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, file);
console.log(`Wrote ${ds.length} shapes, ${pens.length} pen strokes → ${OUT_FILE}`);
console.log("start x of each stroke:", pens.map((k) => Math.round(parseFloat(k.d.slice(1)))).join(", "));
